"""
Netscape cookies.txt format (the format `yt-dlp --cookies` reads).

This is the only module that knows the file format, in both directions:
  - write_cookie_file():      used by the Firefox export (cookie/firefox.py)
  - summarize_cookie_file():  used for the diagnostic log line (cookie/store.py)

Cookie *values* are written to the file but are never logged or returned
by anything here other than the writer.
"""

import os
import time
from typing import NamedTuple

NETSCAPE_HEADER = "# Netscape HTTP Cookie File\n# Generated by the app. Do not share this file.\n\n"

# If none of these are present, the browser profile is almost certainly not
# signed in to Google/YouTube -- age-restricted videos cannot work.
LOGIN_COOKIE_NAMES = frozenset({"SAPISID", "__Secure-3PSID", "SID", "LOGIN_INFO"})


class Cookie(NamedTuple):
    """One cookie. The field order matches Firefox's moz_cookies columns, so a
    SELECT row can be passed straight to Cookie(*row)."""
    host: str
    path: str
    secure: int
    expiry: int
    name: str
    value: str
    http_only: int

    def to_netscape_line(self) -> str:
        expiry = int(self.expiry or 0)
        if expiry > 10 ** 11:  # defensive: some Firefox versions store milliseconds
            expiry //= 1000
        return "\t".join((
            ("#HttpOnly_" if self.http_only else "") + self.host,
            "TRUE" if self.host.startswith(".") else "FALSE",
            self.path or "/",
            "TRUE" if self.secure else "FALSE",
            str(expiry),
            self.name,
            self.value,
        ))


def has_login_cookie(cookies) -> bool:
    """True if any of the cookies is one that only exists when signed in."""
    return any(c.name in LOGIN_COOKIE_NAMES for c in cookies)


def write_cookie_file(path: str, cookies) -> None:
    """Writes `cookies` to `path` as a Netscape cookies.txt.

    Atomic: the data goes to a temp file first and is moved into place with
    os.replace, so a crash never leaves a half-written cookies.txt behind."""
    tmp_path = path + ".tmp"
    with open(tmp_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(NETSCAPE_HEADER)
        for cookie in cookies:
            f.write(cookie.to_netscape_line() + "\n")
    try:
        os.chmod(tmp_path, 0o600)  # best effort; limited effect on Windows
    except OSError:
        pass
    os.replace(tmp_path, path)


class CookieFileSummary(NamedTuple):
    total: int
    expired: int
    login_names: frozenset  # the LOGIN_COOKIE_NAMES that are present in the file


def summarize_cookie_file(path: str) -> CookieFileSummary:
    """Counts the cookies in a Netscape file without keeping any values.
    Raises OSError if the file cannot be read."""
    total = expired = 0
    login = set()
    now = time.time()
    with open(path, encoding="utf-8", errors="replace") as f:
        for raw in f:
            line = raw.rstrip("\r\n")
            if line.startswith("#HttpOnly_"):
                line = line[len("#HttpOnly_"):]
            elif not line.strip() or line.startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) < 7:
                continue
            total += 1
            try:
                exp = int(parts[4])
            except ValueError:
                exp = 0
            if 0 < exp < now:
                expired += 1
            if parts[5] in LOGIN_COOKIE_NAMES:
                login.add(parts[5])
    return CookieFileSummary(total, expired, frozenset(login))
